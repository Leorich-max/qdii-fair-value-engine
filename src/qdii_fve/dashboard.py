"""SYNTHETIC data for the dashboard page — an offline preview built from ``data/sample/``.

The published dashboard (``app/``) is built from real public data by :mod:`qdii_fve.live.update`.
This module produces the same payload shape from the synthetic sample, for offline tests and for
previewing the page without network access; it never writes over ``app/data.js``. The page only
displays these numbers; the one calculation it performs itself, the single-point calculator in
``app/fv.js``, is the same formula as :func:`qdii_fve.fair_value.reconstruct.reconstruct_fair_value`
and is tested against it.

Method (the documented one): ``FV(t) = NAV(D) x U(t)/U(D) x USDCNH(t)/CFETS_parity(D)`` with the NAV
published one session after its valuation date ``D``.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from qdii_fve.fair_value.premium import premium_bps_panel
from qdii_fve.fair_value.reconstruct import reconstruct_series, validation_residuals_bps


def _round(values: pd.Series, digits: int) -> list[float | None]:
    return [None if pd.isna(v) else round(float(v), digits) for v in values]


def compute(sample_dir: str | Path) -> dict[str, pd.DataFrame]:
    """Fair value, premium (bp) and validation residual (bp) per fund, dates x funds."""
    sample = Path(sample_dir)
    bars = pd.read_csv(sample / "SYNTHETIC_daily_bars.csv", parse_dates=["date"])
    nav = pd.read_csv(sample / "SYNTHETIC_nav.csv", parse_dates=["date"])
    und = pd.read_csv(sample / "SYNTHETIC_ndx_underlying.csv", parse_dates=["date"])
    und = und.set_index("date")["close"]
    fx = pd.read_csv(sample / "SYNTHETIC_usdcnh.csv", parse_dates=["date"]).set_index("date")
    close = bars.pivot(index="date", columns="etf_id", values="close")
    nav_pub = nav.pivot(index="date", columns="etf_id", values="nav").reindex(close.index)
    und = und.reindex(close.index)
    fx = fx.reindex(close.index)
    fair = pd.DataFrame(index=close.index, columns=close.columns, dtype=float)
    for f in close.columns:
        fair[f] = reconstruct_series(
            nav_value=nav_pub[f],
            nav_underlying=und.shift(1),
            nav_fx=fx["cfets_parity"].shift(1),
            current_underlying=und,
            current_fx=fx["usdcnh"],
        )
    prem = premium_bps_panel(close, fair)
    realised = nav_pub.shift(-1)  # the NAV that FV(t) predicts is published next session
    resid = pd.DataFrame(
        {f: validation_residuals_bps(fair[f], realised[f]) for f in close.columns}
    ).reindex(close.index)
    return dict(close=close, fair=fair, premium=prem, residual=resid, nav=nav_pub, und=und, fx=fx)


def build_payload(sample_dir: str | Path) -> dict:
    """JSON-ready payload for the page."""
    c = compute(sample_dir)
    dates = [d.strftime("%Y-%m-%d") for d in c["close"].index]
    funds = {}
    for f in c["close"].columns:
        res = c["residual"][f].dropna()
        funds[f] = dict(
            price=_round(c["close"][f], 4),
            fair=_round(c["fair"][f], 4),
            premium_bp=_round(c["premium"][f], 1),
            nav=_round(c["nav"][f], 4),
            residual_std_bp=round(float(res.std()), 2),
            residual_mae_bp=round(float(res.abs().mean()), 2),
        )
    last = c["close"].index[-1]
    prev = c["close"].index[-2]
    first = sorted(funds)[0]
    calc_defaults = dict(
        nav=float(c["nav"].loc[last, first]),
        underlying_ref=float(c["und"].loc[prev]),
        underlying_now=float(c["und"].loc[last]),
        parity_ref=float(c["fx"].loc[prev, "cfets_parity"]),
        fx_now=float(c["fx"].loc[last, "usdcnh"]),
        price=float(c["close"].loc[last, first]),
    )
    return dict(
        synthetic=True,
        note="SYNTHETIC sample generated by scripts/make_synthetic_sample.py; not market data.",
        dates=dates,
        funds=funds,
        underlying=_round(c["und"], 2),
        usdcnh=_round(c["fx"]["usdcnh"], 4),
        cfets_parity=_round(c["fx"]["cfets_parity"], 4),
        calc_defaults=calc_defaults,
    )


def write_data_js(payload: dict, out_path: str | Path) -> Path:
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(payload, separators=(",", ":"), allow_nan=False)
    out.write_text("window.FV_DATA = " + text + ";\n", encoding="utf-8")
    return out


def main(sample_dir: str | Path | None = None, out_path: str | Path | None = None) -> Path:
    root = Path(__file__).resolve().parents[2]
    sample_dir = sample_dir or root / "data" / "sample"
    out_path = out_path or root / "outputs" / "dashboard_synthetic" / "data.js"
    return write_data_js(build_payload(sample_dir), out_path)


if __name__ == "__main__":
    print(main())
